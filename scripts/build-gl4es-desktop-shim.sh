#!/usr/bin/env bash
# Build the gl4es desktop-only forwarding shim.
#
# Coin calls ~88 desktop-GL entry points DIRECTLY (glLightf, glBegin, glMatrixMode,
# glTexEnv*, ...) instead of through its cc_glglue function table. libGLESv2.so
# exports none of them, so they must come from somewhere at link time.
#
# They cannot come from gl4es' libGL.so directly any more: gl4es and libGLESv2.so
# export 142 colliding GL symbols, Android resolves an app's own libraries first,
# and gl4es therefore hijacked Qt's GL calls -- its fixed-pipeline-emulation state
# (varying vec4 Color, src/gl/fpe_shader.c:217) broke Qt's own shaders, leaving the
# 3D viewport blank.
#
# This shim defines ONLY the desktop-only names, each a tail-jump stub (aarch64
# `br`) that forwards to the gl4es image that Coin's cc_dl_open() loads with
# RTLD_LOCAL. A tail jump leaves all argument registers and stack arguments intact,
# so no prototypes are needed. Because none of the names exist in libGLESv2.so the
# shim introduces no symbol collision.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
NDKBIN="$HOME/Library/Android/sdk/ndk/28.2.13676358/toolchains/llvm/prebuilt/darwin-x86_64/bin"
SYSROOT="$NDKBIN/../sysroot"
COIN="$HOME/FreeCAD/src/3rdParty/coin"
OUT="$ROOT/shim/gl4es-desktop-shim"

mkdir -p "$OUT"
cd "$OUT"

# 1. Which GL entry points must the shim provide?
#
#    Take every gl* symbol left undefined by ANY of the app's own libraries and
#    subtract what libGLESv2.so already exports; the remainder is exactly what
#    has to be forwarded to gl4es.
#
#    Scanning only Coin's objects was not enough: libGLU.so also carries
#    undefined GL symbols (it expects them from the GL library the app links,
#    which used to be gl4es), and the first install died at startup with
#        dlopen failed: cannot locate symbol "glTexImage1D" referenced by libGLU.so
#    So the scan covers Coin's objects plus every packaged .so.
COIN_BUILD="${COIN_BUILD:-$ROOT/build/freecad-gui-qt683/src/3rdParty/coin}"
JNILIBS="${JNILIBS:-$ROOT/android-app/jniLibs/arm64-v8a}"

"$NDKBIN/llvm-nm" -D --defined-only \
  "$SYSROOT/usr/lib/aarch64-linux-android/24/libGLESv2.so" \
  | awk '{print $NF}' | sort -u > gles.txt

: > coin_calls.txt
if [ -d "$COIN_BUILD" ]; then
  find "$COIN_BUILD" -name '*.o' -print0 2>/dev/null \
    | xargs -0 "$NDKBIN/llvm-nm" -u 2>/dev/null \
    | awk '$1 == "U" {print $2}' | grep -E '^gl[A-Z]' >> coin_calls.txt || true
  echo "from Coin objects: $(sort -u coin_calls.txt | wc -l)"
fi

if [ -d "$JNILIBS" ]; then
  for so in "$JNILIBS"/*.so; do
    [ -e "$so" ] || continue
    # `|| true` is required: with `set -e` + `pipefail`, the grep in this pipeline
    # returns 1 for any library that has no undefined gl* symbol, which would kill
    # the whole script before the shim is generated.
    { "$NDKBIN/llvm-nm" -D -u "$so" 2>/dev/null \
        | awk '{print $NF}' | grep -E '^gl[A-Z]' >> coin_calls.txt; } || true
  done
  echo "from packaged .so: $(sort -u coin_calls.txt | wc -l)"
fi

# 1b. Names Coin resolves by STRING, not by link-time symbol.
#
#     Coin's glue does  PROC(w, glActiveTexture)  which expands to
#     cc_glglue_getprocaddress(w, "glActiveTexture") -- a runtime string lookup.
#     An object-file scan can therefore never see these names, and the first
#     attempt missed exactly the five that matter:
#         glClientActiveTexture glMultiTexCoord2f glMultiTexCoord2fv
#         glMultiTexCoord3fv    glMultiTexCoord4fv
#     glglue_init() then hit this and silently disarmed multitexturing:
#         if (w->glActiveTexture) {
#           if (!w->glClientActiveTexture || !w->glMultiTexCoord2f || ...)
#             w->glActiveTexture = NULL;     <-- then the first draw jumps to 0
#         }
#     So also collect every NAME passed to PROC() in Coin's glue sources.
if [ -d "$COIN/src/glue" ]; then
  grep -rhoE 'PROC\([a-z_]+, *[A-Za-z0-9_]+\)' "$COIN/src/glue" 2>/dev/null \
    | sed -E 's/PROC\([a-z_]+, *([A-Za-z0-9_]+)\)/\1/' \
    | grep -E '^gl[A-Z]' >> coin_calls.txt || true
  echo "after PROC() names: $(sort -u coin_calls.txt | wc -l)"
fi

if [ ! -s coin_calls.txt ]; then
  grep -rhoE '\bgl[A-Z][A-Za-z0-9_]*\s*\(' "$COIN/src" 2>/dev/null \
    | sed 's/[ (]*$//' >> coin_calls.txt
  echo "fallback source scan: $(sort -u coin_calls.txt | wc -l)"
fi
sort -u coin_calls.txt -o coin_calls.txt

# Symbols libGLESv2.so does not provide must come from the shim. glError and
# glGetInteger are source-scan artefacts, not real entry points.
comm -23 coin_calls.txt gles.txt | grep -vE '^glError$|^glGetInteger$' > symbols.txt
echo "desktop-only symbols: $(wc -l < symbols.txt)"

# 2. Generate the stubs and the slot-filling table.
/usr/bin/python3 - <<'PY'
names = [l.strip() for l in open("symbols.txt") if l.strip()]
with open("gl4es_desktop_shim.S", "w") as f:
    f.write("""/* Auto-generated by scripts/build-gl4es-desktop-shim.sh -- do not edit. */
    .text
    .macro GL4ES_STUB name, idx
    .globl \\name
    .type  \\name, %function
\\name:
    adrp x16, gl4es_slots
    add  x16, x16, #:lo12:gl4es_slots
    ldr  x16, [x16, #(8 * \\idx)]
    br   x16
    .endm
""")
    for i, n in enumerate(names):
        f.write(f"    GL4ES_STUB {n}, {i}\n")
    # .hidden is required: the stubs reach the table with adrp/add, and a
    # preemptible (default-visibility) symbol cannot be addressed that way when the
    # static archive is linked into a shared library -- ld.lld rejects it with
    # "relocation R_AARCH64_ADR_PREL_PG_HI21 cannot be used against symbol
    # 'gl4es_slots'". Hiding it makes the relocation resolve locally at link time.
    f.write("\n    .bss\n    .globl gl4es_slots\n    .hidden gl4es_slots\n    .align 3\ngl4es_slots:\n")
    f.write(f"    .zero {8 * len(names)}\n")
    f.write('    .section .note.GNU-stack,"",%progbits\n')

with open("gl4es_desktop_shim.c", "w") as f:
    f.write("""/* Auto-generated by scripts/build-gl4es-desktop-shim.sh -- do not edit. */
#include <dlfcn.h>
#include <stdio.h>
#include <stdarg.h>
#include <string.h>

extern void *gl4es_slots[];

/* Android app stderr is not wired to logcat, so these diagnostics have to go
   through __android_log_write, resolved with dlsym (liblog.so is always mapped
   into the process, so no -llog link dependency is needed). */
static void shim_log(const char *fmt, ...)
{
    typedef int (*lg_fn)(int, const char *, const char *);
    static lg_fn lg = NULL;
    static int tried = 0;
    char buf[768];
    va_list ap;
    if (!tried) { tried = 1; lg = (lg_fn)dlsym(RTLD_DEFAULT, "__android_log_write"); }
    if (!lg) return;
    va_start(ap, fmt);
    vsnprintf(buf, sizeof(buf), fmt, ap);
    va_end(ap);
    lg(6, "FreeCAD.shim", buf);
}

static const char *const gl4es_names[] = {
""")
    for n in names:
        f.write(f'    "{n}",\n')
    f.write(f"""}};

enum {{ GL4ES_SLOT_COUNT = {len(names)} }};

__attribute__((constructor))
static void gl4es_desktop_shim_init(void)
{{
    /* Resolve libGL.so by ABSOLUTE PATH next to this library.
     *
     * dlopen("libGL.so") by soname is not reliable here: the app's native lib dir
     * is only searched for libraries the loader already knows about, and a bare
     * soname that also exists as a system name can be resolved or refused in ways
     * that differ per ROM. libCoin.so and libGL.so are packaged side by side in the
     * APK's lib/<abi>/ directory, so ask dladdr() where this very library lives and
     * open the sibling file by its full path. That cannot be ambiguous.
     */
    Dl_info info;
    char altpath[512];
    void *h = NULL;

    if (dladdr((void *)(size_t)&gl4es_slots, &info) && info.dli_fname) {{
        const char *slash = strrchr(info.dli_fname, '/');
        if (slash) {{
            size_t dirlen = (size_t)(slash - info.dli_fname) + 1;
            if (dirlen + sizeof("libGL.so") < sizeof(altpath)) {{
                memcpy(altpath, info.dli_fname, dirlen);
                strcpy(altpath + dirlen, "libGL.so");
                h = dlopen(altpath, RTLD_LAZY | RTLD_LOCAL);
                shim_log("dlopen(%s) -> %p", altpath, h);
            }}
        }}
    }}
    if (!h) {{
        h = dlopen("libGL.so", RTLD_LAZY | RTLD_LOCAL);
        shim_log("fallback dlopen(libGL.so) -> %p", h);
    }}
    if (!h) return;
    {{
        int missing = 0;
        int i;
        for (i = 0; i < GL4ES_SLOT_COUNT; ++i) {{
            gl4es_slots[i] = dlsym(h, gl4es_names[i]);
            if (!gl4es_slots[i]) {{ if (missing < 5) shim_log("missing %s", gl4es_names[i]); missing++; }}
        }}
        shim_log("resolved %d/%d symbols", GL4ES_SLOT_COUNT - missing, GL4ES_SLOT_COUNT);
    }}
}}

""")
PY

# 3. Compile and archive.
"$NDKBIN/clang" --target=aarch64-none-linux-android24 --sysroot="$SYSROOT" \
  -fPIC -c gl4es_desktop_shim.S -o shim_asm.o
"$NDKBIN/clang" --target=aarch64-none-linux-android24 --sysroot="$SYSROOT" \
  -fPIC -O2 -c gl4es_desktop_shim.c -o shim_c.o
"$NDKBIN/llvm-ar" rcs libgl4es_desktop_shim.a shim_asm.o shim_c.o

# 4. Fail loudly if any stub collides with GLES2 -- that would defeat the whole point.
conflicts=$(comm -12 <("$NDKBIN/llvm-nm" --defined-only libgl4es_desktop_shim.a \
                        | awk '$2=="T" && $3 ~ /^gl/ {print $3}' | sort -u) gles.txt | wc -l)
if [ "$conflicts" -ne 0 ]; then
  echo "ERROR: shim exports $conflicts symbol(s) that libGLESv2.so also exports" >&2
  exit 1
fi
echo "built $OUT/libgl4es_desktop_shim.a ($(wc -l < symbols.txt) stubs, 0 conflicts)"
