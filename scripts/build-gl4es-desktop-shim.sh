#!/usr/bin/env bash
# Build the gl4es desktop-only forwarding shim.
#
# Coin calls ~88 desktop-GL entry points DIRECTLY (glLightf, glBegin, glMatrixMode,
# glTexEnv*, ...) instead of through its cc_glglue function table. libGLESv2.so
# exports none of them, so they must come from somewhere at link time.
#
# They cannot come from gl4es' libGL.so directly any more: gl4es and libGLESv2.so
# export 142 colliding GL symbols, Android resolves an app's own libraries first,
# and gl4es therefore hijacked Qt's GL calls -- its fixed-pipeline-emulation state
# (varying vec4 Color, src/gl/fpe_shader.c:217) broke Qt's own shaders, leaving the
# 3D viewport blank.
#
# This shim defines ONLY the desktop-only names, each a tail-jump stub (aarch64
# `br`) that forwards to the gl4es image that Coin's cc_dl_open() loads with
# RTLD_LOCAL. A tail jump leaves all argument registers and stack arguments intact,
# so no prototypes are needed. Because none of the names exist in libGLESv2.so the
# shim introduces no symbol collision.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
NDKBIN="$HOME/Library/Android/sdk/ndk/28.2.13676358/toolchains/llvm/prebuilt/darwin-x86_64/bin"
SYSROOT="$NDKBIN/../sysroot"
COIN="$HOME/FreeCAD/src/3rdParty/coin"
OUT="$ROOT/shim/gl4es-desktop-shim"

mkdir -p "$OUT"
cd "$OUT"

# 1. Which GL entry points does Coin need at LINK time that libGLESv2.so lacks?
#
#    Grepping the sources is not reliable -- the calls are spread over nodes/,
#    actions/, elements/, caches/, glue/, ... and the first attempt missed
#    glTexCoord4fv, glBitmap, glRasterPos3f and friends. Ask the object files
#    instead: every gl* symbol left undefined by Coin's own objects is a symbol
#    the linker will demand, and libGLESv2.so is what can satisfy the rest.
COIN_BUILD="${COIN_BUILD:-$ROOT/build/freecad-gui-qt683/src/3rdParty/coin}"

"$NDKBIN/llvm-nm" -D --defined-only \
  "$SYSROOT/usr/lib/aarch64-linux-android/24/libGLESv2.so" \
  | awk '{print $NF}' | sort -u > gles.txt

if [ -d "$COIN_BUILD" ]; then
  find "$COIN_BUILD" -name '*.o' -print0 2>/dev/null \
    | xargs -0 "$NDKBIN/llvm-nm" -u 2>/dev/null \
    | awk '$1 == "U" {print $2}' | grep -E '^gl[A-Z]' | sort -u > coin_calls.txt
  echo "undefined gl* symbols in Coin objects: $(wc -l < coin_calls.txt)"
else
  # Fall back to scanning the sources if the build tree is not there yet.
  grep -rhoE '\bgl[A-Z][A-Za-z0-9_]*\s*\(' \
    "$COIN/src" 2>/dev/null | sed 's/[ (]*$//' | sort -u > coin_calls.txt
  echo "undefined gl* symbols from source scan (build tree absent): $(wc -l < coin_calls.txt)"
fi

# Symbols libGLESv2.so does not provide must come from the shim. glError and
# glGetInteger are source-scan artefacts, not real entry points.
comm -23 coin_calls.txt gles.txt | grep -vE '^glError$|^glGetInteger$' > symbols.txt
echo "desktop-only symbols: $(wc -l < symbols.txt)"

# 2. Generate the stubs and the slot-filling table.
/usr/bin/python3 - <<'PY'
names = [l.strip() for l in open("symbols.txt") if l.strip()]
with open("gl4es_desktop_shim.S", "w") as f:
    f.write("""/* Auto-generated by scripts/build-gl4es-desktop-shim.sh -- do not edit. */
    .text
    .macro GL4ES_STUB name, idx
    .globl \\name
    .type  \\name, %function
\\name:
    adrp x16, gl4es_slots
    add  x16, x16, #:lo12:gl4es_slots
    ldr  x16, [x16, #(8 * \\idx)]
    br   x16
    .endm
""")
    for i, n in enumerate(names):
        f.write(f"    GL4ES_STUB {n}, {i}\n")
    # .hidden is required: the stubs reach the table with adrp/add, and a
    # preemptible (default-visibility) symbol cannot be addressed that way when the
    # static archive is linked into a shared library -- ld.lld rejects it with
    # "relocation R_AARCH64_ADR_PREL_PG_HI21 cannot be used against symbol
    # 'gl4es_slots'". Hiding it makes the relocation resolve locally at link time.
    f.write("\n    .bss\n    .globl gl4es_slots\n    .hidden gl4es_slots\n    .align 3\ngl4es_slots:\n")
    f.write(f"    .zero {8 * len(names)}\n")
    f.write('    .section .note.GNU-stack,"",%progbits\n')

with open("gl4es_desktop_shim.c", "w") as f:
    f.write("""/* Auto-generated by scripts/build-gl4es-desktop-shim.sh -- do not edit. */
#include <dlfcn.h>
#include <stdio.h>

extern void *gl4es_slots[];

static const char *const gl4es_names[] = {
""")
    for n in names:
        f.write(f'    "{n}",\n')
    f.write(f"""}};

enum {{ GL4ES_SLOT_COUNT = {len(names)} }};

__attribute__((constructor))
static void gl4es_desktop_shim_init(void)
{{
    /* Same soname cc_dl_open() uses, so bionic returns the same image. */
    void *h = dlopen("libGL.so", RTLD_LAZY | RTLD_LOCAL);
    if (!h) {{
        fprintf(stderr, "gl4es-desktop-shim: dlopen(libGL.so): %s\\n", dlerror());
        return;
    }}
    for (int i = 0; i < GL4ES_SLOT_COUNT; ++i) {{
        gl4es_slots[i] = dlsym(h, gl4es_names[i]);
        if (!gl4es_slots[i])
            fprintf(stderr, "gl4es-desktop-shim: missing %s\\n", gl4es_names[i]);
    }}
}}
""")
PY

# 3. Compile and archive.
"$NDKBIN/clang" --target=aarch64-none-linux-android24 --sysroot="$SYSROOT" \
  -fPIC -c gl4es_desktop_shim.S -o shim_asm.o
"$NDKBIN/clang" --target=aarch64-none-linux-android24 --sysroot="$SYSROOT" \
  -fPIC -O2 -c gl4es_desktop_shim.c -o shim_c.o
"$NDKBIN/llvm-ar" rcs libgl4es_desktop_shim.a shim_asm.o shim_c.o

# 4. Fail loudly if any stub collides with GLES2 -- that would defeat the whole point.
conflicts=$(comm -12 <("$NDKBIN/llvm-nm" --defined-only libgl4es_desktop_shim.a \
                        | awk '$2=="T" && $3 ~ /^gl/ {print $3}' | sort -u) gles.txt | wc -l)
if [ "$conflicts" -ne 0 ]; then
  echo "ERROR: shim exports $conflicts symbol(s) that libGLESv2.so also exports" >&2
  exit 1
fi
echo "built $OUT/libgl4es_desktop_shim.a ($(wc -l < symbols.txt) stubs, 0 conflicts)"
